import static java.lang.Character.*;
import static java.lang.Math.*;

public class Exercise1
{
   char upper, lower;
   double sqrt1, sqrt2;
   
   // start methods
   public static char toUppercase(char upper)
   {
      return Character.toUpperCase(upper);
   }
   public static char toLowercase(char lower)
   {
      return Character.toLowerCase(lower);
   }
   public static double toSqrt1(double sqrt1)
   {
      return Math.sqrt(sqrt1);
   }
   public static double toSqrt2(double sqrt2)
   {
      return Math.sqrt(sqrt2);
   }
   // end methods
}
